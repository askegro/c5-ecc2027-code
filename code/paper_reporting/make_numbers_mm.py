import json, glob, numpy as np
C = json.load(open('posthoc_mm_contrast.json')); CO = ('cold', 'nominal', 'hot', 'aged'); out = {}
R = {v: [json.load(open(f)) for f in sorted(glob.glob(f'posthoc_mm/{v}/*.json'))] for v in ('hyst', 'asym', 'base')}
f2 = lambda x: f'{x:.2f}'
def med(v, c, arm, k):
    if k == 'cge': return float(np.median([r['rec']['s4786'][arm]['rmse_mv'] for r in R[v] if r['cond'] == c]))
    if k == 'v2': return float(np.median([r['v2'][arm]['rmse_mv'] for r in R[v] if r['cond'] == c]))
for v in ('hyst', 'asym'):
    for k in ('cge', 'v2'):
        vals = [med(v, c, 'C1', k) for c in CO]; out[f'mm.{v}.{k}.C1.range'] = f'{min(vals):.2f}--{max(vals):.2f}'
    out['mm.n.' + v] = str(len(R[v]))
nl = lambda key, cs=CO: min(C[key[0]]['contrasts'][key[1]][c]['n_lower'] for c in cs)
mh = lambda key, cs=CO: max(C[key[0]]['contrasts'][key[1]][c]['p_holm'] for c in cs)
g = lambda key, c, f: C[key[0]]['contrasts'][key[1]][c][f]
k = ('hyst', 'cge_vs_v2_C1'); out['mm.hyst.v2.nlow'] = str(nl(k))
k2 = ('hyst', 'cge_vs_linear_C1'); out['mm.hyst.lin.nlow'] = str(nl(k2)); out['mm.hyst.holm'] = f'{max(mh(k), mh(k2)):.3f}'
k = ('asym', 'cge_vs_v2_C1'); rest = CO[1:]
out['mm.asym.v2.nlow.rest'] = str(nl(k, rest)); out['mm.asym.v2.holm.rest'] = f'{mh(k, rest):.3f}'
out['mm.asym.v2.cold.diff'] = f2(g(k, 'cold', 'median')); out['mm.asym.v2.cold.nhigh'] = str(g(k, 'cold', 'n_higher'))
k = ('asym', 'cge_vs_linear_C1'); out['mm.asym.lin.cold.diff'] = f2(g(k, 'cold', 'median')); out['mm.asym.lin.cold.nhigh'] = str(g(k, 'cold', 'n_higher'))
d = [abs(r['rec']['s4786'][a]['rmse_mv'] - r['linear'][a]) for r in R['asym'] if r['cond'] != 'cold' for a in ('C1', 'C2')]
out['mm.asym.lin.same'] = f'{max(d):.3f}'
out['mm.asym.v2.C2.holm.other'] = f"{min(C['asym']['contrasts']['cge_vs_v2_C2'][c]['p_holm'] for c in ('cold','nominal','aged')):.2f}"
k = ('base', 'cge_vs_passive_eq_C1'); out['mm.eq.C1.range'] = f"{min(abs(g(k, c, 'median')) for c in CO):.2f}--{max(abs(g(k, c, 'median')) for c in CO):.2f}"
out['mm.eq.C1.nlow'] = str(nl(k)); out['mm.eq.C1.holm'] = f'{mh(k):.3f}'
k = ('base', 'cge_vs_passive_eq_C2'); out['mm.eq.C2.holm.min'] = f"{min(C['base']['contrasts']['cge_vs_passive_eq_C2'][c]['p_holm'] for c in CO):.2f}"
k2 = ('base', 'passive_eq_vs_passive_C1'); out['mm.eq.half.cold'] = f2(g(k2, 'cold', 'median'))
lines = ['% GENERATED by make_numbers_mm.py. Do not edit by hand.'] + [r'\expandafter\def\csname num@%s\endcsname{%s}' % kv for kv in out.items()]
open('numbers_mm.tex', 'w').write('\n'.join(lines) + '\n'); print(json.dumps(out, indent=0))
